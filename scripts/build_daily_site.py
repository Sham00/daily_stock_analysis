def _render_section(doc: ReportDoc, idx: int) -> tuple[str, str]:
    anchor = f"section-{idx}"
    html = markdown2.markdown(doc.body, extras=["fenced-code-blocks", "tables", "strike", "header-ids"])
    section = f"<section id='{anchor}' class='section'><h2>{doc.section}</h2><div class='meta'>{doc.title}</div><div class='prose'>{html}</div></section>"
    toc = f"<a href='#{anchor}'>{doc.section}</a>"
    return section, toc


def main() -> None:
    docs = _find_reports()
    SITE_DIR.mkdir(parents=True, exist_ok=True)
    day_dir = SITE_DIR / "daily" / DATE_KEY
    day_dir.mkdir(parents=True, exist_ok=True)

    sections: list[str] = []
    toc: list[str] = []
    if docs:
        for idx, doc in enumerate(docs, start=1):
            section, toc_link = _render_section(doc, idx)
            sections.append(section)
            toc.append(toc_link)
    else:
        sections.append("<section class='section'><h2>No report generated</h2><div class='prose'><p>No markdown reports were found in <code>reports/</code> for this run.</p></div></section>")
        toc.append("<a href='#'>No report generated</a>")

    title = f"Daily trading report — {DATE_KEY}"
    subtitle = f"Portfolio actions, trade tickets, and Gemini deep analysis for {DATE_KEY}."
    html = _html_template(title, subtitle, sections, "".join(toc))
    (day_dir / "index.html").write_text(html, encoding="utf-8")
    (SITE_DIR / "index.html").write_text(html, encoding="utf-8")

    report_url = f"https://{OWNER.lower()}.github.io/{REPO}/daily/{DATE_KEY}/"
    (SITE_DIR / "report_url.txt").write_text(report_url, encoding="utf-8")
    (SITE_DIR / "manifest.json").write_text(json.dumps({"date": DATE_KEY, "url": report_url}, indent=2), encoding="utf-8")
    print(report_url)


if __name__ == "__main__":
    main()
