#!/usr/bin/env python3
from __future__ import annotations

import json
import os
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Iterable

import markdown2

PROJECT_ROOT = Path(__file__).resolve().parent.parent
REPORTS_DIR = PROJECT_ROOT / "reports"
SITE_DIR = PROJECT_ROOT / "site"
OWNER = os.getenv("GITHUB_REPOSITORY_OWNER", "Sham00")
REPO = os.getenv("GITHUB_REPOSITORY", "Sham00/daily_stock_analysis").split("/", 1)[-1]
BRANCH = os.getenv("GITHUB_REF_NAME", "main")
DATE_KEY = datetime.utcnow().strftime("%Y-%m-%d")


@dataclass
class ReportDoc:
    title: str
    path: Path
    body: str
    section: str


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _find_reports() -> list[ReportDoc]:
    docs: list[ReportDoc] = []
    if not REPORTS_DIR.exists():
        return docs

    for path in sorted(REPORTS_DIR.glob("report_*.md"), reverse=True):
        docs.append(ReportDoc(title=f"Daily stock analysis ({path.stem.replace('report_', '')})", path=path, body=_read(path), section="Deep analysis"))
        break

    for path in sorted(REPORTS_DIR.glob("market_review_*.md"), reverse=True):
        docs.append(ReportDoc(title=f"Market review ({path.stem.replace('market_review_', '')})", path=path, body=_read(path), section="Market review"))
        break

    for path in sorted(REPORTS_DIR.glob("trade_tickets_*.md"), reverse=True):
        docs.append(ReportDoc(title=f"Trade tickets ({path.stem.replace('trade_tickets_', '')})", path=path, body=_read(path), section="Trade tickets"))
        break

    return docs


